const sample = document.querySelector('#sample-grid');
const cells = sampleIndices.map(index => {
  const cell = document.createElement('span');
  cell.title = sample.dataset.indexLabel + ' ' + index;
  sample.append(cell);
  return cell;
});
const sampleButtons = document.querySelectorAll('button[data-sample]');

function showSample(numbers) {
  cells.forEach((cell, i) => {
    const index = sampleIndices[i];
    cell.style.backgroundColor = numbers ? '#202a34' : 'rgb(' + rgb.slice(index * 3, index * 3 + 3).join(',') + ')';
    cell.textContent = numbers ? index : '';
  });
}
showSample(false);
for (const button of sampleButtons) {
  button.addEventListener('click', () => {
    for (const item of sampleButtons) item.setAttribute('aria-pressed', String(item === button));
    showSample(button.dataset.sample === 'index');
  });
}

for (const group of document.querySelectorAll('[data-figure]')) {
  const figure = group.closest('figure');
  const image = figure.querySelector('img');
  const caption = figure.querySelector('figcaption');
  const buttons = group.querySelectorAll('button');
  for (const button of buttons) {
    button.addEventListener('click', () => {
      for (const item of buttons) item.setAttribute('aria-pressed', String(item === button));
      image.src = button.dataset.image;
      caption.textContent = button.dataset.caption;
    });
  }
}

